#!/usr/bin/env bash
# Generate per-arch vmlinux headers from github.com/libbpf/vmlinux.h
# plus a vmlinux.h dispatcher.
#
# Usage: gen-vmlinux.sh [-o OUT_DIR] [-r GIT_REF] ARCH...
#   ARCH: x86 | arm64 | arm | riscv | s390 | powerpc | loongarch
#   e.g.  gen-vmlinux.sh -o bpf/include -r c3291284 x86 arm64

set -euo pipefail

OUT_DIR="bpf/include"
REF="main"
REPO="https://github.com/libbpf/vmlinux.h.git"

while getopts "o:r:" opt; do
  case $opt in
    o) OUT_DIR=$OPTARG ;;
    r) REF=$OPTARG ;;
    *) exit 1 ;;
  esac
done
shift $((OPTIND - 1))
(( $# )) || { echo "usage: $0 [-o OUT_DIR] [-r GIT_REF] ARCH..." >&2; exit 1; }

work=$(mktemp -d)
trap 'rm -rf "$work"' EXIT

git -C "$work" init -q
git -C "$work" fetch -q --depth 1 "$REPO" "$REF"
git -C "$work" checkout -q FETCH_HEAD

mkdir -p "$OUT_DIR"

for arch in "$@"; do
  src="$work/include/$arch/vmlinux.h"
  [[ -e $src ]] || { echo "unknown arch: $arch" >&2; exit 1; }
  guard="__VMLINUX_GENERATED_${arch^^}_H__"
  # Rename bpftool's __VMLINUX_H__ guard so it doesn't collide with the dispatcher's.
  sed "s/\b__VMLINUX_H__\b/${guard}/g" "$(readlink -f "$src")" \
    > "$OUT_DIR/vmlinux_generated_${arch}.h"
  echo "wrote $OUT_DIR/vmlinux_generated_${arch}.h"
done

{
  echo "/* SPDX-License-Identifier: GPL-2.0 */"
  echo "/* GENERATED by gen-vmlinux.sh — do not edit. */"
  echo "#ifndef __VMLINUX_DISPATCH_H__"
  echo "#define __VMLINUX_DISPATCH_H__"
  echo
  kw="#if"
  for f in $(ls "$OUT_DIR"/vmlinux_generated_*.h | sort); do
    arch=$(basename "$f" .h)
    arch=${arch#vmlinux_generated_}
    echo "$kw defined(__TARGET_ARCH_${arch})"
    echo "#include \"vmlinux_generated_${arch}.h\""
    kw="#elif"
  done
  echo "#else"
  echo "#error \"__TARGET_ARCH_* not supported\""
  echo "#endif"
  echo
  echo "#endif"
} > "$OUT_DIR/vmlinux.h"
echo "wrote $OUT_DIR/vmlinux.h"